export function t(lang: Language, key: string): string {
  return TRANSLATIONS[lang][key] ?? TRANSLATIONS.en[key] ?? key;
}

export function getActionLabel(lang: Language, action: ActionType): string {
  return t(lang, action);
}

export function getRiskLabel(lang: Language, risk: RiskLevel): string {
  if (risk === 'high') return t(lang, 'riskHigh');
  if (risk === 'medium') return t(lang, 'riskMedium');
  return t(lang, 'riskLow');
}

export function getRoleLabel(lang: Language, role: UserRole): string {
  switch (role) {
    case 'farmer':
      return t(lang, 'roleFarmer');
    case 'fpo_admin':
      return t(lang, 'roleFpoAdmin');
    case 'buyer':
      return t(lang, 'roleBuyer');
    case 'system_admin':
      return t(lang, 'roleSystemAdmin');
  }
}
